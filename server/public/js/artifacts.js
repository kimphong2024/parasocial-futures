// Artifacts from the future — six objects per published scenario. Each card
// carries the object's photograph, the words printed on it, what it assumes,
// the evidence it grows from, and the verbatim prompt that produced the image.
import { api, esc } from "./api.js";
import { renderNav } from "./nav.js";

const $ = (id) => document.getElementById(id);
let data = [], filter = "";

function card(sc, a) {
  return `<article class="artifact">
    <figure class="art-shot">
      <img src="/img/artifacts/${esc(sc.archetype)}-${esc(a.slug)}.jpg" alt="${esc(a.title)}" loading="lazy"
           onerror="this.closest('.art-shot').classList.add('missing')">
      <figcaption class="art-type">${esc(a.type)}</figcaption>
    </figure>
    <div class="art-body">
      <h3>${esc(a.title)}</h3>
      <pre class="art-specimen">${esc(a.specimen)}</pre>
      <p class="art-blurb">${esc(a.blurb)}</p>
      <p class="caption art-evidence"><strong>Grows from</strong> ${esc(a.evidence)}</p>
      <details class="art-prompt">
        <summary class="caption">Image prompt — verbatim${a.image_model ? ` · ${esc(a.image_model)}` : ""}</summary>
        <p class="caption">${esc(a.image_prompt_used || a.image_prompt)}</p>
      </details>
    </div>
  </article>`;
}

function render() {
  const shown = filter ? data.filter((s) => s.archetype === filter) : data;
  $("artGroups").innerHTML = shown.map((sc) => `
    <section class="art-group">
      <div class="art-grouphead">
        <span class="label">${esc(sc.archetype)} · ${sc.artifacts.length} objects</span>
        <h3>${esc(sc.title)}</h3>
        <a class="caption" href="/scenario?id=${sc.id}">Read the scenario these came from →</a>
      </div>
      <div class="art-grid">${sc.artifacts.map((a) => card(sc, a)).join("")}</div>
    </section>`).join("");
  document.querySelectorAll("#artFilter .pill").forEach((p) =>
    p.classList.toggle("active", p.dataset.arch === filter));
}

async function load() {
  const j = await api("/api/artifacts");
  data = j.scenarios;
  if (!data.length) {
    $("artGroups").innerHTML = `<div class="empty-note">No artifacts yet — they are generated per published scenario.</div>`;
    return;
  }
  $("artFilter").innerHTML =
    `<button class="pill active" data-arch="">All four futures</button>` +
    data.map((s) => `<button class="pill" data-arch="${esc(s.archetype)}">${esc(s.title)}</button>`).join("");
  $("artFilter").addEventListener("click", (e) => {
    const b = e.target.closest(".pill");
    if (!b) return;
    filter = b.dataset.arch;
    render();
  });
  const n = data.reduce((t, s) => t + s.artifacts.length, 0);
  const model = data[0]?.artifacts?.[0]?.image_model;
  $("artNote").textContent =
    `${n} artifacts across ${data.length} published scenarios. Each object, and the words printed on it, were written by Claude from that scenario's own CLA layers — never improvised by the image model. ` +
    (model
      ? `The photographs were then generated by ${model}, which renders the supplied text legibly; the full composed prompt behind every image is disclosed on the object itself.`
      : `The photographs were generated from the prompts disclosed on each object.`);
  render();
}

renderNav("/artifacts");
load();
